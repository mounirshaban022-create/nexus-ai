/** Strip everything but digits (E.164 without the leading +). */
export function normalizeWaNumber(raw: string): string {
  return (raw || '').replace(/[^\d]/g, '')
}

/** Public, token-safe representation for the UI. */
export function toPublicAccount(account: WhatsAppAccountRecord): PublicWhatsAppAccount {
  let tokenPreview = ''
  try {
    const plain = decryptSecret(
      (account as unknown as { accessTokenEnc: string }).accessTokenEnc
    )
    tokenPreview = plain.length > 12 ? `${plain.slice(0, 6)}…${plain.slice(-4)}` : '••••'
  } catch {
    tokenPreview = '••••'
  }
  let allowList: string[] = []
  try {
    const parsed = JSON.parse(account.allowList || '[]')
    if (Array.isArray(parsed)) allowList = parsed.filter((n) => typeof n === 'string')
  } catch {
    /* ignore malformed JSON */
  }
  return {
    id: account.id,
    label: account.label,
    businessName: account.businessName,
    phoneNumberId: account.phoneNumberId,
    displayPhone: account.displayPhone,
    verifyToken: account.verifyToken,
    status: account.status,
    statusMessage: account.statusMessage,
    autoReply: account.autoReply,
    agentPrompt: account.agentPrompt,
    allowList,
    webhookVerified: account.webhookVerified,
    hasToken: true,
    tokenPreview,
    createdAt: account.createdAt.toISOString(),
    updatedAt: account.updatedAt.toISOString(),
  }
}

/** Generate a webhook verify token (32 hex chars). */
export function generateVerifyToken(): string {
  return randomBytes(16).toString('hex')
}

