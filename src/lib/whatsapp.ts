/** Default persona when the user hasn't written a custom one. */
export const DEFAULT_AGENT_PROMPT = `You are the WhatsApp assistant for a small business in Dubai. You reply to customer messages quickly, warmly and professionally.

Rules:
- Keep replies SHORT (under 120 words) — this is WhatsApp, not email.
- Use a friendly, human tone. Light emoji use is fine (max 1-2).
- If you don't know something (prices, availability, addresses), say you'll check and ask for a moment rather than inventing facts.
- Never invent order numbers, payment links or personal data.
- Reply in the same language the customer writes in (English or Arabic).`

/** How many past messages (per customer) the agent remembers. */
const MEMORY_DEPTH = 12

/**
 * Generate an agent reply for an incoming customer message.
 * Builds conversation history from the stored message log, routes
 * through the NEXUS smart-chat pool, and returns WhatsApp-ready text.
 */
export async function generateAgentReply(
  account: WhatsAppAccountRecord,
  fromNumber: string,
  incomingText: string,
  contactName?: string
): Promise<string> {
  // Recent conversation with this customer (oldest → newest)
  const history = await db.whatsAppMessage.findMany({
    where: { fromNumber, direction: { in: ['in', 'out'] } },
    orderBy: { createdAt: 'desc' },
    take: MEMORY_DEPTH,
  })
  history.reverse()

  const persona = account.agentPrompt?.trim() || DEFAULT_AGENT_PROMPT

  const systemPrompt = `${persona}

You are replying inside WhatsApp on behalf of "${account.businessName}".
${contactName ? `The customer's name is ${contactName}.` : ''}
Current date/time context: ${new Date().toISOString()}
Stay concise and WhatsApp-native. Plain text only — no markdown headers, no bullet symbols beyond simple dashes.`

  const messages: Array<{ role: string; content: string }> = [{ role: 'system', content: systemPrompt }]

  for (const msg of history) {
    // Skip the just-saved incoming message — it's appended below as the final user turn
    if (msg.direction === 'in' && msg.body === incomingText && msg.createdAt.getTime() > Date.now() - 15_000) {
      // include it only once (it IS the latest message; history may already contain it)
      const isLast = history[history.length - 1]?.id === msg.id
      if (isLast) continue
    }
    messages.push({
      role: msg.direction === 'in' ? 'user' : 'assistant',
      content: msg.body,
    })
  }

  messages.push({ role: 'user', content: incomingText })

  try {
    const reply = await smartChat(messages, {
      task: 'chat',
      maxTokens: 500,
      temperature: 0.7,
      timeoutMs: 45_000,
    })

    const trimmed = reply.trim()
    if (!trimmed) {
      return "Hi! Thanks for your message — we'll get back to you shortly. 🙏"
    }
    return trimmed
  } catch (error) {
    console.error('[whatsapp] agent reply failed:', error)
    return "Thanks for your message! We received it and will reply personally in a moment. 🙏"
  }
}

