export async function saveInboundMessage(
  accountId: string,
  fromNumber: string,
  toNumber: string,
  body: string,
  waMessageId: string
): Promise<boolean> {
  // Dedupe: Meta retries webhooks aggressively
  const existing = await db.whatsAppMessage.findFirst({
    where: { waMessageId, direction: 'in' },
  })
  if (existing) return false

  await db.whatsAppMessage.create({
    data: {
      accountId,
      fromNumber,
      toNumber,
      direction: 'in',
      body,
      waMessageId,
      status: 'received',
    },
  })
  return true
}

export async function saveOutboundMessage(
  accountId: string,
  fromNumber: string,
  toNumber: string,
  body: string,
  waMessageId: string | null,
  status: string
): Promise<void> {
  await db.whatsAppMessage.create({
    data: {
      accountId,
      fromNumber,
      toNumber,
      direction: 'out',
      body,
      waMessageId: waMessageId ?? undefined,
      status,
    },
  })
}
