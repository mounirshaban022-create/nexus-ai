export interface WaSendResult {
  ok: boolean
  waMessageId?: string
  error?: string
}

/** Send a plain-text WhatsApp message via the Cloud API. */
export async function waSendText(
  account: WhatsAppAccountRecord,
  to: string,
  body: string
): Promise<WaSendResult> {
  const recipient = normalizeWaNumber(to)
  if (!recipient) return { ok: false, error: 'Missing recipient number.' }

  let token: string
  try {
    token = decryptSecret((account as unknown as { accessTokenEnc: string }).accessTokenEnc)
  } catch {
    return { ok: false, error: 'Stored access token is corrupted — reconnect the account.' }
  }

  const text = body.length > WA_TEXT_LIMIT ? `${body.slice(0, WA_TEXT_LIMIT - 1)}…` : body

  try {
    const res = await fetch(`${GRAPH_BASE}/${account.phoneNumberId}/messages`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        messaging_product: 'whatsapp',
        recipient_type: 'individual',
        to: recipient,
        type: 'text',
        text: { preview_url: false, body: text },
      }),
      signal: AbortSignal.timeout(20_000),
    })

    const data = (await res.json().catch(() => ({}))) as {
      messages?: { id: string }[]
      error?: { message?: string; code?: number }
    }

    if (!res.ok) {
      const message = data.error?.message || `Cloud API error (HTTP ${res.status})`
      console.error('[whatsapp] send failed:', message)
      return { ok: false, error: message }
    }

    return { ok: true, waMessageId: data.messages?.[0]?.id }
  } catch (error) {
    const message = error instanceof Error ? error.message : 'Network error contacting Meta'
    console.error('[whatsapp] send error:', message)
    return { ok: false, error: message }
  }
}

/** Mark a customer message as read (blue ticks) — best effort. */
export async function waMarkRead(
  account: WhatsAppAccountRecord,
  messageId: string
): Promise<void> {
  try {
    const token = decryptSecret((account as unknown as { accessTokenEnc: string }).accessTokenEnc)
    await fetch(`${GRAPH_BASE}/${account.phoneNumberId}/messages`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        messaging_product: 'whatsapp',
        status: 'read',
        message_id: messageId,
      }),
      signal: AbortSignal.timeout(10_000),
    })
  } catch {
    /* best-effort — ignore failures */
  }
}

